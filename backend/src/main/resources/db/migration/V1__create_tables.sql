-- 첫 migration: 엔티티 12개가 쓰는 테이블 전체입니다(2026.11.12 O-1).
-- Hibernate가 ddl-auto: create로 만들던 DDL을 그대로 옮겼습니다. 열 이름, 타입, not null, unique, check, 외래 키가 같습니다.
-- 읽기 쉽게 바꾼 것은 세 가지입니다: 테이블을 참조 순서로 놓음, 열을 Entity 필드 순서로 놓음, 외래 키를 열 옆에 바로 적음.
-- 이미 commit 된 이 파일은 고치지 않습니다. 열을 더하거나 바꾸려면 V3__...sql처럼 다음 번호의 새 파일을 만듭니다.

-- Member: 교수와 학생
create table member (
    id bigint generated by default as identity,
    email varchar(255) not null unique,
    password varchar(255),
    name varchar(255) not null,
    member_type varchar(255) not null check (member_type in ('PROFESSOR','STUDENT')),
    privacy_consented_at timestamp(6),
    primary key (id)
);

-- Assignment: 교수가 만든 과제
create table assignment (
    id bigint generated by default as identity,
    title varchar(255) not null,
    start_date date not null,
    end_date date not null,
    professor_id bigint not null references member (id),
    phase varchar(255) not null check (phase in ('RECORDING','EVALUATION')),
    evaluation_started_at timestamp(6),
    primary key (id)
);

-- Team: 과제 안의 조
create table team (
    id bigint generated by default as identity,
    assignment_id bigint not null references assignment (id),
    name varchar(255) not null,
    invite_code varchar(255) unique,
    primary key (id)
);

-- TeamMember: 조 참여 기록. 한 학생은 같은 과제에서 한 조에만 있습니다.
create table team_member (
    id bigint generated by default as identity,
    team_id bigint not null references team (id),
    assignment_id bigint not null references assignment (id),
    member_id bigint not null references member (id),
    leader boolean not null,
    role_name varchar(255),
    role_assigned_at timestamp(6),
    primary key (id),
    unique (assignment_id, member_id)
);

-- RoleHistory: 역할 변경 이력
create table role_history (
    id bigint generated by default as identity,
    team_member_id bigint not null references team_member (id),
    previous_role_name varchar(255) not null,
    previous_role_assigned_at timestamp(6) not null,
    changed_at timestamp(6) not null,
    primary key (id)
);

-- LeaderHistory: 조장 교체 이력
create table leader_history (
    id bigint generated by default as identity,
    team_id bigint not null references team (id),
    previous_leader_id bigint not null references team_member (id),
    new_leader_id bigint not null references team_member (id),
    changed_at timestamp(6) not null,
    primary key (id)
);

-- Deliverable: 산출물. 파일 본문은 MinIO에 있고 여기에는 위치·이름·크기만 둡니다.
create table deliverable (
    id bigint generated by default as identity,
    team_member_id bigint not null references team_member (id),
    role_name varchar(255) not null,
    file_name varchar(255) not null,
    file_size bigint not null,
    storage_key varchar(255) not null,
    uploaded_at timestamp(6) not null,
    deleted_at timestamp(6),
    primary key (id)
);

-- Contribution: 기여 항목
create table contribution (
    id bigint generated by default as identity,
    team_id bigint not null references team (id),
    assignee_id bigint not null references team_member (id),
    title varchar(255) not null,
    created_at timestamp(6) not null,
    report_memo varchar(2000),
    reported_at timestamp(6),
    canceled_at timestamp(6),
    primary key (id)
);

-- Confirmation: 완료확인. 대상은 deliverable_id와 contribution_id 중 하나만 채웁니다.
create table confirmation (
    id bigint generated by default as identity,
    confirmer_id bigint not null references team_member (id),
    deliverable_id bigint references deliverable (id),
    contribution_id bigint references contribution (id),
    confirmed_at timestamp(6) not null,
    canceled_at timestamp(6),
    primary key (id)
);

-- Evaluation: 제출한 동료평가. 같은 평가자가 같은 대상을 두 번 평가하지 못합니다.
create table evaluation (
    id bigint generated by default as identity,
    evaluator_id bigint not null references team_member (id),
    target_id bigint not null references team_member (id),
    goal_sharing integer not null,
    role_fulfillment integer not null,
    encouragement integer not null,
    online_communication integer not null,
    offline_communication integer not null,
    progress_check integer not null,
    comment varchar(2000),
    submitted_at timestamp(6) not null,
    primary key (id),
    unique (evaluator_id, target_id)
);

-- EvaluationDraft: 평가 임시 저장. 점수는 고르지 않았으면 null입니다.
create table evaluation_draft (
    id bigint generated by default as identity,
    evaluator_id bigint not null references team_member (id),
    target_id bigint not null references team_member (id),
    goal_sharing integer,
    role_fulfillment integer,
    encouragement integer,
    online_communication integer,
    offline_communication integer,
    progress_check integer,
    comment varchar(2000),
    saved_at timestamp(6) not null,
    primary key (id),
    unique (evaluator_id, target_id)
);

-- Notification: 화면 안 알림
create table notification (
    id bigint generated by default as identity,
    recipient_id bigint not null references member (id),
    type varchar(255) not null check (type in ('EVALUATION_STARTED','CONTRIBUTION_ASSIGNED','CONTRIBUTION_REPORTED')),
    message varchar(1000) not null,
    team_id bigint not null references team (id),
    created_at timestamp(6) not null,
    read_at timestamp(6),
    primary key (id)
);
