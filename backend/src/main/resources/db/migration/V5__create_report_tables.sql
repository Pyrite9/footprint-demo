-- 보고서와 파트 테이블을 만들고, 알림 종류에 파트 담당 지정을 더합니다(2026.11.25 X-12-1 보고서와 파트 배분).

-- Report: 조장이 만든 보고서. 한 조에 여러 개. 제목은 고치지 않고 행은 지우지 않습니다.
create table report (
    id bigint generated by default as identity,
    team_id bigint not null references team (id),
    title varchar(255) not null,
    created_at timestamp(6) not null,
    primary key (id)
);

-- ReportPart: 보고서의 한 부분과 담당 조원. 취소하면 canceled_at만 채우고 행은 남깁니다.
create table report_part (
    id bigint generated by default as identity,
    report_id bigint not null references report (id),
    assignee_id bigint not null references team_member (id),
    title varchar(255) not null,
    created_at timestamp(6) not null,
    canceled_at timestamp(6),
    primary key (id)
);

-- notification.type의 check 제약에 REPORT_PART_ASSIGNED를 더합니다.
-- V1에서 이름 없이 만든 check 제약은 PostgreSQL이 "테이블_칸_check"라는 이름을 붙입니다. 그 이름으로 지우고 다시 만듭니다.
alter table notification drop constraint notification_type_check;
alter table notification add constraint notification_type_check
    check (type in ('EVALUATION_STARTED','CONTRIBUTION_ASSIGNED','CONTRIBUTION_REPORTED','REPORT_PART_ASSIGNED'));
